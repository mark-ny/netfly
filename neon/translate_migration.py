#!/usr/bin/env python3
"""Translate a Supabase migration to the Neon names used in neon/001_schema.sql.

usage: python3 neon/translate_migration.py supabase/migrations/<file>.sql > neon/<out>.sql
Only renames identifiers; review the output before running it on a Neon branch.
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()
out = src.replace("auth.users", 'neon_auth."user"')
out = re.sub(r"\banon\b", "anonymous", out)
out = re.sub(r"\bservice_role\b", "netfly_service", out)
header = (
    "-- DRAFT translation of " + sys.argv[1] + " for Neon. NOT APPLIED, NOT TESTED against Neon.\n"
    "-- Generated by neon/translate_migration.py (renames auth.users, anon, service_role only).\n"
    "-- Run on a Neon branch after neon/001_schema.sql.\n"
)
sys.stdout.write(header + out)
